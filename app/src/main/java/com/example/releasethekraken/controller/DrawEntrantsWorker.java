/**
 * Worker that performs the lottery draw for an event.
 *
 * This background task retrieves the event and its list of entrants,
 * randomly selects winners based on the event capacity, saves the
 * accepted entrants to Firestore, and sends notifications to the winners.
 *
 * The worker is triggered through WorkManager and runs asynchronously
 * while database operations are handled through repository callbacks.
 */
public class DrawEntrantsWorker extends Worker {

    public DrawEntrantsWorker(@NonNull Context context, @NonNull WorkerParameters params) {
        super(context, params);
    }

    /**
     * Executes the background task for drawing event entrants.
     *
     * @return Result.success() if the worker starts correctly,
     *         or Result.failure() if the event ID is missing.
     */
    @NonNull
    @Override
    public Result doWork() {

        String eventId = getInputData().getString("eventId");

        if (eventId == null) {
            return Result.failure();
        }

        EventRepository eventRepo = new EventRepository();
        WaitingListRepository waitingListRepo = new WaitingListRepository();
        NotificationService notifService = new NotificationService(new NotificationRepository());
        WaitingListService waitingListService = new WaitingListService(waitingListRepo);

        // Step 1: Get event details from Firestore
        eventRepo.getEventById(eventId, new EventRepository.EventCallback() {
            @Override
            public void onSuccess(Event event) {

                // Step 2: Get all entrants for this event
                waitingListRepo.getAllEntrants(event.getEventId(), new WaitingListRepository.EntrantsCallback() {
                    @Override
                    public void onResult(ArrayList<String> entrants) {

                        if (entrants.isEmpty()) {
                            // No entrants, nothing to draw
                            return;
                        }

                        // Step 3: Draw winners
                        int capacity = event.getCapacity(); // Make sure Event has capacity field
                        ArrayList<String> winners = new LotteryManager().drawEntrants(event, entrants, capacity);

                        // Step 4: Save winners to Firestore
                        waitingListRepo.saveAcceptedEntrants(event.getEventId(), winners, new WaitingListRepository.CompletionCallback() {
                            @Override
                            public void onSuccess() {
                                // Step 5: Send notifications to winners
                                for (String winnerId : winners) {
                                    notifService.sendWinNotification(event, winnerId, new NotificationService.NotificationCallback() {
                                        @Override
                                        public void onResult(NotificationService.NotificationResult result) {
                                            // Log success or update analytics
                                        }

                                        @Override
                                        public void onError(Exception e) {
                                            e.printStackTrace(); // Log failure, but don't block
                                        }
                                    });
                                }
                            }

                            @Override
                            public void onError(Exception e) {
                                e.printStackTrace();
                            }
                        });

                    }

                    @Override
                    public void onError(Exception e) {
                        e.printStackTrace();
                    }
                });

            }

            @Override
            public void onError(Exception e) {
                e.printStackTrace();
            }
        });

        // Worker itself returns success; async callbacks handle Firestore operations
        return Result.success();
    }
}